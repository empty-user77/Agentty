//! UI strings in English, Korean, Japanese and Simplified Chinese.

use crate::settings::{settings, Language};
use gpui::App;

/// Translated string for the current language. Unknown keys fall back to the key itself.
pub fn t(cx: &App, key: &'static str) -> &'static str {
    tr(settings(cx).language, key)
}

/// Translated string with `{n}` / `{name}` placeholders filled in.
pub fn tf(cx: &App, key: &'static str, args: &[(&str, &str)]) -> String {
    let mut text = t(cx, key).to_string();
    for (name, value) in args {
        text = text.replace(&format!("{{{name}}}"), value);
    }
    text
}

pub fn tr(language: Language, key: &'static str) -> &'static str {
    let Some(row) = lookup(key) else { return key };
    match language.resolved() {
        Language::En | Language::System => row[0],
        Language::Ko => row[1],
        Language::Ja => row[2],
        Language::Zh => row[3],
    }
}

macro_rules! strings {
    ($($key:literal => [$en:literal, $ko:literal, $ja:literal, $zh:literal]),* $(,)?) => {
        #[cfg(test)]
        const KEYS: &[&str] = &[$($key),*];
        fn lookup(key: &str) -> Option<[&'static str; 4]> {
            match key {
                $($key => Some([$en, $ko, $ja, $zh]),)*
                _ => None,
            }
        }
    };
}

